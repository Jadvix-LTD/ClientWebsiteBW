import type { Metadata } from "next";
import { absoluteUrl, site } from "./site";
import { services } from "./services";

type PageMetaInput = { title: string; description: string; path: string; absoluteTitle?: boolean };

/** Per-page metadata with a self-referencing canonical URL and matching social tags. */
export function pageMeta({ title, description, path, absoluteTitle }: PageMetaInput): Metadata {
  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      locale: "en_GB",
      siteName: "Beaver and Weaver Engineering Services",
      url: path,
      title,
      description,
      images: [shareImage],
    },
    twitter: { card: "summary_large_image", title, description, images: [shareImage.url] },
  };
}

/** Generated by app/opengraph-image.tsx; listed explicitly so page-level openGraph keeps it. */
const shareImage = {
  url: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: `Beaver and Weaver Engineering Services: ${site.headline}`,
};

export function organizationSchema() {
  return {
    "@context": "https://schema.org",
    "@type": "ProfessionalService",
    "@id": absoluteUrl("/#organization"),
    name: site.name,
    alternateName: site.shortName,
    slogan: site.tagline,
    description: site.description,
    url: site.url,
    logo: absoluteUrl("/brand/logo.png"),
    image: absoluteUrl("/images/hero-bim.svg"),
    email: site.email,
    ...(site.phone ? { telephone: site.phone } : {}),
    address: { "@type": "PostalAddress", addressCountry: "GB" },
    areaServed: [
      { "@type": "Country", name: "United Kingdom" },
      { "@type": "Place", name: "Europe" },
      { "@type": "Place", name: "North America" },
    ],
    knowsAbout: [
      "Building Information Modelling",
      "Revit modelling",
      "CAD drafting",
      "Structural steel detailing",
      "Precast concrete detailing",
      "Rebar detailing",
      "MEP coordination",
      "Clash detection",
      "Facade detailing",
      "Scan to BIM",
    ],
    hasOfferCatalog: {
      "@type": "OfferCatalog",
      name: "BIM and engineering services",
      itemListElement: services.map((s) => ({
        "@type": "Offer",
        itemOffered: { "@type": "Service", name: s.title, url: absoluteUrl(`/services/${s.slug}`) },
      })),
    },
  };
}

export function breadcrumbSchema(items: { name: string; path: string }[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: items.map((it, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: it.name,
      item: absoluteUrl(it.path),
    })),
  };
}
